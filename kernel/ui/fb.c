// ------------------------------------------------------------------

void fb_init(void)
{
    uint32_t *src = (uint32_t*)0x5000;
    fb_info.phys_base = src[0];
    fb_info.width     = src[1];
    fb_info.height    = src[2];
    fb_info.bpp       = src[3];

    // Recompute pitch instead of trusting the bootloader's value.
    // Round bpp up to a whole byte count (15bpp still occupies 2 bytes).
    fb_info.pitch     = fb_info.width * ((fb_info.bpp + 7) / 8);

    // Read colour masks from bootloader
    fb_info.red_mask_size   = src[5];
    fb_info.red_field_pos   = src[6];
    fb_info.green_mask_size = src[7];
    fb_info.green_field_pos = src[8];
    fb_info.blue_mask_size  = src[9];
    fb_info.blue_field_pos  = src[10];

    fb_clear(0x000000);
    fb_swap();
}

// Number of whole bytes one pixel occupies for the current mode. 24bpp is
// exactly 3; 15/16bpp are 2; 32bpp is 4. Never assume 4 - the mode the
// bootloader requests (VESA 0x118) is actually 24bpp.
static inline uint32_t fb_bytes_per_pixel(void)
{
    return (fb_info.bpp + 7) / 8;
}

// Write the low `bpp` bytes of a converted pixel value into the backbuffer
// at a byte offset, least-significant byte first (matches how the VBE
// field positions pack bits within those bytes on this little-endian CPU).
static inline void fb_write_pixel_at(uint32_t byte_offset, uint32_t converted)
{
    uint32_t bypp = fb_bytes_per_pixel();
    uint8_t *p = back_buffer + byte_offset;
    for (uint32_t i = 0; i < bypp; i++)
    {
        p[i] = (uint8_t)(converted >> (8 * i));
    }
}

void fb_putpixel(uint32_t x, uint32_t y, uint32_t color)
{
    if (x >= fb_info.width || y >= fb_info.height)
    {
        return;
    }
    uint32_t offset = y * fb_info.pitch + x * fb_bytes_per_pixel();
    fb_write_pixel_at(offset, fb_convert_color(color));
}

void fb_fillrect(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint32_t color)
{
    uint32_t converted = fb_convert_color(color);
    uint32_t bypp = fb_bytes_per_pixel();
    for (uint32_t row = y; row < y + h && row < fb_info.height; row++)
    {
        uint32_t row_offset = row * fb_info.pitch;
        for (uint32_t col = x; col < x + w && col < fb_info.width; col++)
        {
            fb_write_pixel_at(row_offset + col * bypp, converted);
        }
    }
}

void fb_clear(uint32_t color)
{
    uint32_t converted = fb_convert_color(color);
    uint32_t bypp = fb_bytes_per_pixel();
    for (uint32_t y = 0; y < fb_info.height; y++)
    {
        uint32_t row_offset = y * fb_info.pitch;
        for (uint32_t x = 0; x < fb_info.width; x++)
        {
            fb_write_pixel_at(row_offset + x * bypp, converted);
        }
    }
}

void fb_swap(void)
{
    uint32_t bytes = fb_info.height * fb_info.pitch;
    uint8_t *dst = (uint8_t*)fb_info.phys_base;
    uint8_t *src = back_buffer;
    for (uint32_t i = 0; i < bytes; i++)
    {
        dst[i] = src[i];
    }
}

void fb_draw_char(uint32_t x, uint32_t y, char c, uint32_t fg, uint32_t bg)
{
    unsigned char ch = (unsigned char)c;
    if (ch < 32 || ch > 127)
    {
        ch = 32;
    }
    const unsigned char *glyph = font8x16[ch - 32];
    for (int row = 0; row < 16; row++)
    {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; col++)
        {
            if (bits & (1 << (7 - col)))
            {
                fb_putpixel(x + col, y + row, fg);
            }
            else
            {
                fb_putpixel(x + col, y + row, bg);
            }
        }
    }
}

void fb_draw_string(uint32_t x, uint32_t y, const char *s, uint32_t fg, uint32_t bg)
{
    while (*s)
    {
        fb_draw_char(x, y, *s++, fg, bg);
        x += 8;
        if (x + 8 > fb_info.width)
        {
            x = 0;
            y += 16;
        }
    }
}