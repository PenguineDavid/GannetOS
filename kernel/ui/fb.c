static inline uint32_t fb_convert_color(uint32_t color)
{
    // Extract RGB components from the input (assume 0xRRGGBB)
    uint32_t r = (color >> 16) & 0xFF;
    uint32_t g = (color >> 8)  & 0xFF;
    uint32_t b = (color >> 0)  & 0xFF;

    // Pack them according to the VBE masks
    uint32_t out = 0;
    out |= (r >> (8 - fb_info.red_mask_size)) << fb_info.red_field_pos;
    out |= (g >> (8 - fb_info.green_mask_size)) << fb_info.green_field_pos;
    out |= (b >> (8 - fb_info.blue_mask_size)) << fb_info.blue_field_pos;
    // If the framebuffer has an alpha channel, we could set it to 0xFF here,
    // but we'll leave it as zero (or we can set it if bpp == 32)
    if (fb_info.bpp == 32)
    {
        out |= 0xFF000000; // set alpha to opaque if 32-bit
    }
    return out;
}


// ------------------------------------------------------------------
